import { Column, ColumnGroup, Row, Cell, CellValue } from '@/types/dashboard';

const createCell = (
  rowId: string,
  columnId: string,
  raw: string | number,
  type: CellValue['type'] = 'text',
  formula?: string
): Cell => ({
  id: `${rowId}-${columnId}`,
  rowId,
  columnId,
  value: {
    raw,
    type,
    formula,
    displayValue: type === 'percentage' 
      ? `${typeof raw === 'number' ? Math.round(raw * 100) : raw}%`
      : type === 'number' || type === 'currency'
        ? new Intl.NumberFormat('pt-BR').format(Number(raw))
        : String(raw),
  },
});

